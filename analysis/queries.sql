-- ------------------------------------------------------------
-- Q1 ⭐ วันที่ไม่ได้เงิน เกิดจากอะไร  (โจทย์หลักของโปรเจกต์)
-- ------------------------------------------------------------
SELECT
    COALESCE(no_sale_reason, 'ยังไม่ได้ระบุ')                   AS สาเหตุ,
    COUNT(*)                                                    AS จำนวนวัน,
    ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (), 1)          AS เปอร์เซ็นต์
FROM v_day
WHERE orders = 0
GROUP BY 1
ORDER BY จำนวนวัน DESC;


-- ------------------------------------------------------------
-- Q2 ⭐ ของถูกหรือของแพง คุ้มกว่ากัน
--
--     สมมติฐาน: ของถูกให้กำไรต่อครั้งสูงกว่า เพราะตั้งราคาเป็นทอดๆ
--     (RAP 100 กับ RAP 500 ขายราคาใกล้กัน แต่ทุนต่างกัน 5 เท่า)
--     ถ้าจริง แปลว่าควรเน้นของถูก ไม่ใช่ไล่ล่าของแพง
-- ------------------------------------------------------------
SELECT
    token_band                              AS ช่วงราคา_Token,
    COUNT(*)                                AS ครั้ง,
    ROUND(AVG(price_baht), 0)               AS ขายเฉลี่ย,
    ROUND(AVG(cost_baht), 1)                AS ทุนเฉลี่ย,
    ROUND(AVG(profit_baht), 1)              AS กำไรต่อครั้ง,
    ROUND(SUM(profit_baht), 0)              AS กำไรรวม,
    ROUND(AVG(markup_x), 2)                 AS ขายได้กี่เท่าของทุน,
    ROUND(AVG(profit_per_token), 4)         AS กำไรต่อ_Token
FROM v_sale
GROUP BY token_band
ORDER BY token_band;


-- ------------------------------------------------------------
-- Q3 ⭐ ชั่วโมงไหนขายได้มากที่สุด
--
--     เดิมตรงนี้เป็น "ประเภทไหนทำเงินดีที่สุด" ซึ่งใช้คอลัมน์ category
--     ที่ถูกถอดออก 27 ก.ย. 2026 เพราะไม่เคยมีใครกรอกเลยสักครั้งใน 89 ออเดอร์
--     เปลี่ยนมาใช้ logged_at แทน ซึ่งบอทบันทึกให้เองทุกครั้ง ข้อมูลครบ 100%
--
--     substr ตำแหน่ง 12-13 คือชั่วโมง ใช้ได้ทั้ง SQLite และ Postgres
--     SQLite เก็บเป็น '2026-09-27T13:05:00+07:00'
--     Postgres แปลงเป็นข้อความได้ '2026-09-27 13:05:00+07'
--     ต่างกันแค่ตัวที่ 11 (T กับเว้นวรรค) ชั่วโมงอยู่ตำแหน่งเดียวกัน
--
--     ⚠️ ข้อควรระวัง: นี่คือ "เวลาที่กดบันทึก" ไม่ใช่ "เวลาที่ขายได้จริง"
--     ถ้าจดรวดเดียวตอนดึก ตัวเลขจะกองอยู่ตอนดึกทั้งที่ขายตอนเย็น
-- ------------------------------------------------------------
SELECT
    substr(CAST(logged_at AS text), 12, 2) AS ชั่วโมงที่จด,
    COUNT(*)                               AS ครั้ง,
    ROUND(SUM(profit_baht), 0)             AS กำไรรวม,
    ROUND(AVG(profit_baht), 1)             AS กำไรต่อครั้ง
FROM v_sale
GROUP BY 1
ORDER BY 1;


-- ------------------------------------------------------------
-- Q4 ⭐ วันดีกับวันแย่ ต่างกันเพราะอะไร
--
--     โจทย์ที่ตั้งไว้ตอนแรกคือ "วันที่ไม่มีรายได้เกิดจากอะไร"
--     แต่พอเก็บข้อมูลจริง 13 วัน ไม่มีวันไหนได้ศูนย์เลยสักวัน
--     โจทย์จริงจึงเปลี่ยนเป็น "ทำไมบางวันได้ 205 บางวันได้ 1,417" (ต่าง 7 เท่า)
--
--     คำถามนี้แยกได้ 2 ทาง และตารางนี้บอกว่าเป็นทางไหน
--       ขายได้น้อยครั้ง      -> ปัญหาอยู่ที่ต้นทาง (คนทักน้อย / ไม่ได้โพสต์)
--       กำไรต่อครั้งต่ำ      -> ปัญหาอยู่ที่ของที่ขาย (ได้แต่ออเดอร์เล็ก)
-- ------------------------------------------------------------
SELECT
    log_date                               AS วัน,
    orders                                 AS ขายกี่ครั้ง,
    ROUND(profit_baht, 0)                  AS กำไรวันนั้น,
    ROUND(profit_baht / NULLIF(orders, 0), 0) AS กำไรต่อครั้ง,
    inquiries                              AS คนทัก,
    close_rate_pct                         AS ปิดการขาย_pct
FROM v_day
WHERE orders > 0
ORDER BY profit_baht DESC;


-- ------------------------------------------------------------
-- Q5 ⭐ รับ "เหมา" มาย่อยเอง ดีกว่าซื้อ Token จริงมั้ย
--
--     บนกระดาษเหมาได้เรท 17-25 เทียบกับพ่อค้า 11 ดูดีกว่ามาก
--     แต่เหมาได้มาเป็น "ไอเทม" ไม่ใช่ Token ต้องตั้งบูธขายก่อน
--     และมี 2 อย่างที่กินเรทไป
--       1) ค่าธรรมเนียมบูธ 1% — เลี่ยงไม่ได้ แต่คิดล่วงหน้าได้
--       2) ชิ้นที่ขายไม่ออก — ตัวนี้แหละความเสี่ยงจริง เพราะเงินจมทั้งก้อน
--     คอลัมน์ เรทจริง คือคำตอบว่าคุ้มจริงมั้ย
-- ------------------------------------------------------------
SELECT
    CASE kind WHEN 'lot' THEN 'รับเหมามาย่อยเอง'
              ELSE 'ซื้อ Token จากพ่อค้า' END AS แหล่งของ,
    COUNT(*)                                AS ครั้ง,
    ROUND(SUM(baht), 0)                     AS จ่ายไปรวม,
    ROUND(AVG(rate_on_paper), 2)            AS เรทที่เห็นตอนกดซื้อ,
    ROUND(AVG(rate_expected), 2)            AS เรทหลังหักค่าบูธ,
    ROUND(AVG(rate_actual), 2)              AS เรทจริงหลังย่อยขาย,
    ROUND(AVG(sold_through_pct), 1)         AS ขายออกไปแล้วกี่_pct,
    SUM(CASE WHEN kind = 'lot' AND tokens_realised IS NULL THEN 1 ELSE 0 END)
                                            AS ล็อตที่ยังย่อยไม่เสร็จ
FROM v_purchase
GROUP BY kind;


-- ------------------------------------------------------------
-- Q5b ⭐ กำไรเงินสดจริง เทียบกับกำไรที่คิดรายออเดอร์
--
--      กำไรเงินสด = เงินลูกค้าโอนเข้า − เงินที่จ่ายซื้อของ  ← ต้องตรงกับยอดกรุงไทย
--      กำไรรายออเดอร์ = ผลรวมของ (ราคาขาย − ทุนประมาณ)
--      ผลต่าง = ของที่ซื้อมาแล้วยังขายไม่ออก ไม่ใช่การจดผิด
--      เป็นบวก = เดือนนี้ซื้อของตุนไว้เกินที่ขายออก
--      เป็นลบ  = เดือนนี้ขายของที่ซื้อมาตั้งแต่เดือนก่อน
-- ------------------------------------------------------------
WITH เงินเข้า AS (
    SELECT substr(sold_on, 1, 7) AS เดือน,
           SUM(price_baht)       AS รับเงิน,
           SUM(profit_baht)      AS กำไรรายออเดอร์
    FROM v_sale GROUP BY 1
),
เงินออก AS (
    SELECT substr(bought_on, 1, 7) AS เดือน,
           SUM(baht)               AS จ่ายซื้อของ
    FROM purchase GROUP BY 1
)
SELECT
    COALESCE(i.เดือน, o.เดือน)                          AS เดือน,
    ROUND(COALESCE(i.รับเงิน, 0), 0)                     AS รับเงิน,
    ROUND(COALESCE(o.จ่ายซื้อของ, 0), 0)                 AS จ่ายซื้อของ,
    ROUND(COALESCE(i.รับเงิน,0) - COALESCE(o.จ่ายซื้อของ,0), 0) AS กำไรเงินสดจริง,
    ROUND(COALESCE(i.กำไรรายออเดอร์, 0), 0)              AS กำไรรายออเดอร์,
    ROUND(COALESCE(i.กำไรรายออเดอร์,0)
          - (COALESCE(i.รับเงิน,0) - COALESCE(o.จ่ายซื้อของ,0)), 0) AS ของที่ยังค้างอยู่
FROM เงินเข้า i
FULL OUTER JOIN เงินออก o ON i.เดือน = o.เดือน
ORDER BY เดือน;


-- ------------------------------------------------------------
-- Q6  เรท Token กระทบกำไรแค่ไหน
-- ------------------------------------------------------------
SELECT
    token_rate                              AS เรท,
    COUNT(*)                                AS ครั้ง,
    SUM(tokens_spent)                       AS Token_ที่ใช้,
    ROUND(SUM(cost_baht), 0)                AS ทุนรวม,
    -- ถ้าได้เรท 11 ทุกครั้ง จะประหยัดไปเท่าไหร่
    ROUND(SUM(cost_baht) - SUM(tokens_spent) / 11.0, 0) AS ส่วนต่างถ้าได้เรท11
FROM v_sale
GROUP BY token_rate
ORDER BY token_rate DESC;


-- ------------------------------------------------------------
-- Q7 ⭐ กำไรกระจุกอยู่ที่ไม่กี่วันแค่ไหน
--
--     เดิมตรงนี้เป็น "ส่วนลดที่ให้ไปทั้งหมด" ซึ่งใช้ list_baht
--     ที่ถูกถอดออกเพราะไม่เคยกรอกเลย (0/89)
--
--     คำถามใหม่สำคัญกว่ามาก เพราะกฎข้อ 6 ใน CLAUDE.md บอกว่า
--     "กำไรรายวันกระจายตัวเบ้มาก ห้ามสรุปจากค่าเฉลี่ยอย่างเดียว"
--     ตารางนี้วัดความเบ้นั้นเป็นตัวเลข
--
--     ถ้ากำไรครึ่งเดือนมาจาก 3 วัน แปลว่าธุรกิจพึ่งวันใหญ่ ไม่ใช่วันปกติ
--     ซึ่งเปลี่ยนวิธีวางแผนทั้งหมด — ต้องหาว่าวันใหญ่เกิดจากอะไร
--     ไม่ใช่พยายามดันวันปกติให้ดีขึ้นทีละนิด
-- ------------------------------------------------------------
WITH เรียง AS (
    SELECT log_date, profit_baht
    FROM v_day
    WHERE orders > 0
),
รวม AS (SELECT SUM(profit_baht) AS ทั้งหมด, COUNT(*) AS กี่วัน FROM เรียง)
SELECT
    (SELECT กี่วัน FROM รวม)                        AS วันที่ขายได้,
    ROUND((SELECT ทั้งหมด FROM รวม), 0)             AS กำไรทั้งหมด,
    ROUND(MAX(profit_baht), 0)                      AS วันที่ดีที่สุด,
    ROUND(MIN(profit_baht), 0)                      AS วันที่แย่ที่สุด,
    ROUND(AVG(profit_baht), 0)                      AS เฉลี่ยต่อวัน,
    ROUND(100.0 * MAX(profit_baht)
          / NULLIF((SELECT ทั้งหมด FROM รวม), 0), 1) AS วันดีสุดคิดเป็น_pct
FROM เรียง;


-- ------------------------------------------------------------
-- Q8  เปิดร้านกี่วัน วันที่เปิดทำเงินเฉลี่ยเท่าไหร่ (รายเดือน)
-- ------------------------------------------------------------
SELECT
    substr(log_date, 1, 7)                                      AS เดือน,
    COUNT(*)                                                    AS วันที่บันทึก,
    SUM(CASE WHEN shop_open = 1 THEN 1 ELSE 0 END)              AS วันที่เปิดร้าน,
    SUM(CASE WHEN orders > 0 THEN 1 ELSE 0 END)                 AS วันที่ขายได้,
    ROUND(SUM(profit_baht), 0)                                  AS กำไรรวม,
    ROUND(SUM(profit_baht) / NULLIF(SUM(CASE WHEN orders > 0 THEN 1 ELSE 0 END), 0), 0)
                                                                AS กำไรเฉลี่ยวันที่ขายได้
FROM v_day
GROUP BY เดือน
ORDER BY เดือน;


-- ------------------------------------------------------------
-- Q9  ยังขาดอีกเท่าไหร่ถึงเป้า 8,800 และต้องขายอีกกี่ครั้ง
-- ------------------------------------------------------------
WITH เดือนนี้ AS (
    SELECT COALESCE(SUM(profit_baht), 0) AS กำไร,
           COUNT(*)                      AS ครั้ง
    FROM v_sale
    -- เทียบเป็นข้อความ 'YYYY-MM' เพราะ CURRENT_DATE กับ substr มีทั้งใน
    -- SQLite และ Postgres  ส่วน strftime มีแต่ใน SQLite อย่างเดียว
    WHERE substr(CAST(sold_on AS text), 1, 7)
        = substr(CAST(CURRENT_DATE AS text), 1, 7)
)
SELECT
    ROUND(กำไร, 0)                                      AS กำไรเดือนนี้,
    8800 - ROUND(กำไร, 0)                               AS ขาดอีก,
    ครั้ง                                                AS ขายไปแล้ว,
    ROUND(กำไร / NULLIF(ครั้ง, 0), 1)                   AS กำไรเฉลี่ยต่อครั้ง,
    CEIL((8800 - กำไร) / NULLIF(กำไร / NULLIF(ครั้ง, 0), 0)) AS ต้องขายอีกกี่ครั้ง
FROM เดือนนี้;


-- ------------------------------------------------------------
-- Q10 กำไรสะสมรายวัน เทียบเส้นเป้า (ใช้ทำกราฟใน Power BI)
--     ใช้ window function SUM() OVER (ORDER BY ...)
-- ------------------------------------------------------------
SELECT
    log_date                                                    AS วันที่,
    ROUND(profit_baht, 0)                                       AS กำไรวันนั้น,
    ROUND(SUM(profit_baht) OVER (
        PARTITION BY substr(log_date, 1, 7) ORDER BY log_date
    ), 0)                                                       AS กำไรสะสมในเดือน,
    ROUND(290.0 * CAST(substr(log_date, 9, 2) AS INTEGER), 0)    AS เส้นเป้าสะสม
FROM v_day
ORDER BY log_date;
